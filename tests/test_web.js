const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const path = require("node:path");
const context = vm.createContext({console, setTimeout, clearTimeout, AbortController, TypeError, Map});
vm.runInContext(fs.readFileSync(path.join(__dirname, "../web/app.js"), "utf8"), context);

(async () => {
  assert.equal(vm.runInContext('escapeHtml("<img src=x onerror=evil()> & \\\"note\\\"")', context), "&lt;img src=x onerror=evil()&gt; &amp; &quot;note&quot;");
  let calls = 0;
  context.fetch = async () => { calls++; return calls === 1 ? {ok:false,status:503,json:async()=>({error:"unavailable"})} : {ok:true,json:async()=>({answer:"ok"})}; };
  assert.equal((await vm.runInContext('requestJson("/api/question")', context)).answer, "ok");
  assert.equal(calls, 2);
  calls = 0;
  context.fetch = async () => { calls++; return {ok:false,status:400,json:async()=>({error:"invalid question"})}; };
  await assert.rejects(vm.runInContext('requestJson("/api/question")', context), /invalid question/);
  assert.equal(calls, 1);
  calls = 0;
  context.fetch = async () => { calls++; throw new TypeError("connection lost"); };
  await assert.rejects(vm.runInContext('requestJson("/api/question")', context), /connection lost/);
  assert.equal(calls, 2);
  context.fetch = (_url, options) => new Promise((_resolve, reject) => options.signal.addEventListener("abort", () => { const error = new Error("abort"); error.name = "AbortError"; reject(error); }));
  await assert.rejects(vm.runInContext('requestJson("/api/question", {}, {attempts:1,timeoutMs:1})', context), /timed out/);
  const elements = new Map();
  context.document = {getElementById(id){ if (!elements.has(id)) elements.set(id, {textContent:"",innerHTML:"",value:""}); return elements.get(id); }};
  const id = '<img src=x onerror="evil()">';
  context.fixture = {route:"Mumbai-Pune",route_type:"Short",week_of:"2025-01-06",shipment_count:3,cost_per_tonne_km:3,history_change_percent:20,history_average:2.5,history_week_count:8,peer_average:2.4,peer_count:1,reason:"Source-backed.",flagged:"No (justified)",matched_note_id:id,retrieved_notes:[{note_id:id,eligible:true,check:"valid"}]};
  context.source = {note_id:id,date:"2025-01-06",applies_to:"Mumbai-Pune",text:"Higher freight costs."};
  vm.runInContext('notesById = new Map([[source.note_id, source]]); chart = () => {}; table = () => {}; inspect(fixture);', context);
  assert.ok(elements.get("detail-content").innerHTML.includes("&lt;img"));
  assert.ok(!elements.get("detail-content").innerHTML.includes("<img"));
  context.gapRows = [{week_of:"2025-01-06"}, {week_of:"2025-01-13"}, {week_of:"2025-02-03"}];
  assert.equal(vm.runInContext('calendarX(gapRows, 1, 0, 400)', context), 100);
  assert.equal(vm.runInContext('calendarX([gapRows[0]], 0, 43, 681)', context), 43);
  context.another = {...context.fixture, route:"Delhi-Jaipur", week_of:"2025-01-06"};
  vm.runInContext('report = {rows:[fixture, another]}; selectRoute("Delhi-Jaipur");', context);
  assert.equal(elements.get("detail-route").textContent, "Delhi-Jaipur");
  assert.equal(elements.get("route-select").value, "Delhi-Jaipur");
  console.log("Frontend checks: 8 passed (escaping, retry, client error, network failure, timeout, evidence rendering, calendar spacing, route selection).");
})().catch((error) => { console.error(error); process.exitCode = 1; });
